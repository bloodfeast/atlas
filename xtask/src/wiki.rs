//! The wiki step of `cargo xtask release`: publishes `wiki/` to the public
//! repository's wiki, `<public repo>.wiki.git`, one commit per release.
//!
//! 1. Stage: every page of the exported tree's `wiki/` (the release's own
//!    `git archive`, never the working tree), plus the generated pages
//!    ([`GENERATED`]): `Changelog.md` is CHANGELOG.md without its title.
//!    A generated page committed under `wiki/` is refused.
//! 2. Leak check: the staged pages against the denylist, as the export is.
//! 3. Clone the wiki remote. GitHub creates a wiki's repository only when
//!    its first page is made in the web UI; a remote that is not there
//!    stops the release with that instruction. The release never creates
//!    it any other way.
//! 4. Replace the clone's pages with the staged ones and commit under the
//!    public identity (`atlas vX.Y.Z wiki`); a release that changes no page
//!    makes no commit. Every address in the wiki's history must be the
//!    public one.
//! 5. Push, only with `--push` (and ATLAS_PUBLISH for a remote that is not
//!    a local folder, checked by the caller). Without it, and always with
//!    `--dry-run`, the release prints what would change.
//!
//! `--build-only` never reaches this step.

use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

type R<T = ()> = Result<T, String>;

/// Pages the release writes; `wiki/` must not hold them.
pub const GENERATED: &[&str] = &["Changelog"];

/// The wiki remote of a repository remote: `X.git` -> `X.wiki.git`, `X` ->
/// `X.wiki.git` (GitHub's layout; a local bare repository follows it too).
pub fn wiki_remote(remote: &str) -> String {
    let r = remote.trim_end_matches(['/', '\\']);
    format!("{}.wiki.git", r.strip_suffix(".git").unwrap_or(r))
}

/// The Changelog page: CHANGELOG.md without its `# ` title line (a wiki
/// page shows its name as the title).
pub fn changelog_page(text: &str) -> String {
    let text = text.replace("\r\n", "\n");
    let body = match text.split_once('\n') {
        Some((first, rest)) if first.starts_with("# ") => rest,
        _ => text.as_str(),
    };
    format!("{}\n", body.trim_matches('\n'))
}

/// Copies the pages of `src` (Markdown files at its top level; GitHub
/// wikis are flat) into `out` and writes the generated ones. Returns the
/// page file names, sorted.
pub fn stage_pages(src: &Path, changelog: &str, out: &Path) -> R<Vec<String>> {
    let _ = std::fs::remove_dir_all(out);
    std::fs::create_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;
    let mut names = Vec::new();
    for e in std::fs::read_dir(src).map_err(|e| format!("{}: {e} (the release publishes wiki/)", src.display()))? {
        let e = e.map_err(|e| e.to_string())?;
        let name = e.file_name().to_string_lossy().into_owned();
        if e.file_type().map_err(|e| e.to_string())?.is_dir() {
            return Err(format!("wiki/{name}: a GitHub wiki is flat; pages go directly under wiki/"));
        }
        let Some(stem) = name.strip_suffix(".md") else {
            return Err(format!("wiki/{name}: only .md pages are published"));
        };
        if GENERATED.contains(&stem) {
            return Err(format!("wiki/{name} is generated by the release; remove it from wiki/"));
        }
        std::fs::copy(e.path(), out.join(&name)).map_err(|e| format!("wiki/{name}: {e}"))?;
        names.push(name);
    }
    if !names.iter().any(|n| n == "Home.md") {
        return Err("wiki/ has no Home.md".into());
    }
    std::fs::write(out.join("Changelog.md"), changelog_page(changelog)).map_err(|e| e.to_string())?;
    names.push("Changelog.md".into());
    names.sort();
    Ok(names)
}

/// The public identity commits are made under.
pub struct Ident<'a> {
    /// Author and committer name.
    pub name: &'a str,
    /// Author and committer address.
    pub email: &'a str,
}

/// A wiki clone with the release's pages committed (or nothing to commit).
#[derive(Debug)]
pub struct Prepared {
    /// The clone.
    pub clone: PathBuf,
    /// The wiki remote.
    pub remote: String,
    /// The branch the wiki publishes (GitHub's wikis use `master`).
    pub branch: String,
    /// Whether a commit was made.
    pub changed: bool,
    /// `git diff --stat` of that commit against the wiki as it was.
    pub stat: String,
}

fn git(dir: &Path, args: &[&str]) -> R<String> {
    let o = Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(args)
        .env("GIT_TERMINAL_PROMPT", "0")
        .stdin(Stdio::null())
        .output()
        .map_err(|e| format!("git {}: {e}", args.join(" ")))?;
    if !o.status.success() {
        return Err(format!("git {} failed: {}", args.join(" "), String::from_utf8_lossy(&o.stderr).trim()));
    }
    Ok(String::from_utf8_lossy(&o.stdout).into_owned())
}

/// The branch a remote's HEAD points at: the `ref: refs/heads/NAME` line of
/// `git ls-remote --symref REMOTE HEAD`.
pub fn remote_head(remote: &str) -> Option<String> {
    let o = Command::new("git").args(["ls-remote", "--symref", remote, "HEAD"]).env("GIT_TERMINAL_PROMPT", "0").stdin(Stdio::null()).output().ok()?;
    if !o.status.success() {
        return None;
    }
    parse_symref(&String::from_utf8_lossy(&o.stdout))
}

/// The branch of a `ref: refs/heads/NAME<TAB>HEAD` line.
pub fn parse_symref(out: &str) -> Option<String> {
    out.lines().find_map(|l| l.strip_prefix("ref: refs/heads/")?.strip_suffix("\tHEAD").map(str::to_string))
}

/// The message when the wiki repository is not there yet.
pub fn missing_wiki_message(remote: &str, public_repo: &str) -> String {
    format!(
        "the wiki repository {remote} does not exist yet. GitHub creates it only when the first page is made in the web UI: \
         open https://github.com/{public_repo}/wiki, create any page once (it is replaced by the release), then run the release again"
    )
}

/// Steps 3 and 4: clone `remote` into `work`, replace its pages with
/// `pages` and commit under `ident`.
pub fn prepare(pages: &Path, remote: &str, public_repo: &str, tag: &str, ident: &Ident, work: &Path) -> R<Prepared> {
    let _ = std::fs::remove_dir_all(work);
    let reach = Command::new("git")
        .args(["ls-remote", "-q", remote])
        .env("GIT_TERMINAL_PROMPT", "0")
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map_err(|e| format!("git ls-remote: {e}"))?;
    if !reach.success() {
        return Err(missing_wiki_message(remote, public_repo));
    }
    let parent = work.parent().ok_or("the wiki work folder has no parent")?;
    std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
    let ok = Command::new("git")
        .args(["clone", "-q", remote])
        .arg(work)
        .env("GIT_TERMINAL_PROMPT", "0")
        .stdin(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map_err(|e| format!("git clone: {e}"))?;
    if !ok.success() {
        return Err(format!("cannot clone the wiki {remote}"));
    }
    // A wiki GitHub created has a first commit. One without (a bare test
    // repository, say) starts on master, the branch GitHub's wikis use.
    let has_head = git(work, &["rev-parse", "-q", "--verify", "HEAD"]).is_ok();
    if !has_head {
        git(work, &["symbolic-ref", "HEAD", "refs/heads/master"])?;
    }
    // The branch the remote's HEAD names (GitHub's wikis use master), read
    // with ls-remote rather than assumed; the clone's own HEAD otherwise.
    let branch = match remote_head(remote) {
        Some(b) if has_head => {
            git(work, &["checkout", "-q", &b])?;
            b
        }
        _ => git(work, &["symbolic-ref", "--short", "HEAD"])?.trim().to_string(),
    };
    if has_head {
        git(work, &["rm", "-rq", "--ignore-unmatch", "."])?;
    }
    for e in std::fs::read_dir(pages).map_err(|e| format!("{}: {e}", pages.display()))? {
        let e = e.map_err(|e| e.to_string())?;
        std::fs::copy(e.path(), work.join(e.file_name())).map_err(|e| e.to_string())?;
    }
    git(work, &["add", "-A", "."])?;
    let staged = git(work, &["status", "--porcelain"])?;
    if staged.trim().is_empty() {
        return Ok(Prepared { clone: work.to_path_buf(), remote: remote.into(), branch, changed: false, stat: String::new() });
    }
    let stat = if has_head { git(work, &["diff", "--cached", "--stat", "HEAD"])? } else { git(work, &["diff", "--cached", "--stat", "--root"]).or_else(|_| git(work, &["status", "--short"]))? };
    let msg = format!("atlas {tag} wiki");
    let o = Command::new("git")
        .arg("-C")
        .arg(work)
        .args(["commit", "-q", "-m", &msg])
        .env("GIT_AUTHOR_NAME", ident.name)
        .env("GIT_AUTHOR_EMAIL", ident.email)
        .env("GIT_COMMITTER_NAME", ident.name)
        .env("GIT_COMMITTER_EMAIL", ident.email)
        .stdin(Stdio::null())
        .output()
        .map_err(|e| format!("git commit: {e}"))?;
    if !o.status.success() {
        return Err(format!("the wiki commit failed: {}", String::from_utf8_lossy(&o.stderr).trim()));
    }
    // Only this release's commit is checked: a wiki GitHub created has the
    // first page's commit under the account's own identity.
    let addrs = git(work, &["log", "-1", "--format=%ae%n%ce"])?;
    if addrs.lines().any(|a| a != ident.email) {
        return Err("the wiki commit carries another address".into());
    }
    Ok(Prepared { clone: work.to_path_buf(), remote: remote.into(), branch, changed: true, stat })
}

/// Step 5: pushes the prepared commit. Nothing to push is not an error.
pub fn push(p: &Prepared) -> R {
    if !p.changed {
        return Ok(());
    }
    git(&p.clone, &["push", "-q", "origin", &format!("HEAD:refs/heads/{}", p.branch)]).map(|_| ())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("atlas-wiki-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    fn sh(dir: &Path, args: &[&str]) -> String {
        git(dir, args).unwrap()
    }

    const ME: Ident = Ident { name: "Pub Lic", email: "pub@example.invalid" };

    #[test]
    fn remotes_and_the_changelog_page() {
        assert_eq!(wiki_remote("https://github.com/acme/tool.git"), "https://github.com/acme/tool.wiki.git");
        assert_eq!(wiki_remote("git@github.com:acme/tool"), "git@github.com:acme/tool.wiki.git");
        assert_eq!(wiki_remote("Z:/stage/pub.git/"), "Z:/stage/pub.wiki.git");
        assert_eq!(parse_symref("ref: refs/heads/master\tHEAD\n0123abcd\tHEAD\n").as_deref(), Some("master"));
        assert_eq!(parse_symref("0123abcd\tHEAD\n"), None);
        assert_eq!(changelog_page("# Changelog\r\n\r\nRule.\r\n\r\n## v0.1.0\r\n\r\n- one\r\n"), "Rule.\n\n## v0.1.0\n\n- one\n");
    }

    #[test]
    fn staging_refuses_generated_nested_and_homeless_wikis() {
        let d = tmp("stage");
        let src = d.join("wiki");
        std::fs::create_dir_all(&src).unwrap();
        std::fs::write(src.join("Home.md"), "home\n").unwrap();
        std::fs::write(src.join("Tools-reference.md"), "tools\n").unwrap();
        let names = stage_pages(&src, "# Changelog\n\n## v1\n\n- x\n", &d.join("out")).unwrap();
        assert_eq!(names, ["Changelog.md", "Home.md", "Tools-reference.md"]);
        assert_eq!(std::fs::read_to_string(d.join("out/Changelog.md")).unwrap(), "## v1\n\n- x\n");
        std::fs::write(src.join("Changelog.md"), "by hand\n").unwrap();
        assert!(stage_pages(&src, "", &d.join("out")).unwrap_err().contains("generated"));
        std::fs::remove_file(src.join("Changelog.md")).unwrap();
        std::fs::create_dir_all(src.join("sub")).unwrap();
        assert!(stage_pages(&src, "", &d.join("out")).unwrap_err().contains("flat"));
        std::fs::remove_dir_all(src.join("sub")).unwrap();
        std::fs::remove_file(src.join("Home.md")).unwrap();
        assert!(stage_pages(&src, "", &d.join("out")).unwrap_err().contains("Home.md"));
        let _ = std::fs::remove_dir_all(&d);
    }

    #[test]
    fn a_missing_wiki_repository_stops_with_the_instruction() {
        let d = tmp("missing");
        std::fs::create_dir_all(d.join("pages")).unwrap();
        let remote = d.join("pub.wiki.git").to_string_lossy().replace('\\', "/");
        let e = prepare(&d.join("pages"), &remote, "acme/tool", "v1.0.0", &ME, &d.join("work")).unwrap_err();
        assert!(e.contains("does not exist yet") && e.contains("https://github.com/acme/tool/wiki"), "{e}");
        assert!(!d.join("pub.wiki.git").exists(), "the release never creates the wiki repository");
        let _ = std::fs::remove_dir_all(&d);
    }

    /// The whole step against local bare repositories: the first page as
    /// GitHub makes it, a release commit, a push, and a second release
    /// that changes nothing.
    #[test]
    fn publishes_one_commit_per_release_to_a_local_bare_wiki() {
        let d = tmp("publish");
        let bare = d.join("pub.wiki.git");
        sh(&d, &["init", "-q", "--bare", "-b", "master", bare.to_str().unwrap()]);
        // The first page, made "in the web UI" under the account's identity.
        let seed = d.join("seed");
        sh(&d, &["clone", "-q", bare.to_str().unwrap(), seed.to_str().unwrap()]);
        std::fs::write(seed.join("Home.md"), "Welcome to the wiki\n").unwrap();
        sh(&seed, &["add", "Home.md"]);
        sh(&seed, &["-c", "user.name=Owner", "-c", "user.email=owner@example.invalid", "commit", "-q", "-m", "Initial Home page"]);
        sh(&seed, &["push", "-q", "origin", "HEAD:refs/heads/master"]);

        let src = d.join("wiki");
        std::fs::create_dir_all(&src).unwrap();
        std::fs::write(src.join("Home.md"), "# atlas\n\n- [[Tools reference]]\n").unwrap();
        std::fs::write(src.join("Tools-reference.md"), "tools\n").unwrap();
        let pages = d.join("pages");
        stage_pages(&src, "# Changelog\n\n## v1.0.0\n\n- one\n", &pages).unwrap();
        let remote = bare.to_string_lossy().replace('\\', "/");
        let p = prepare(&pages, &remote, "acme/tool", "v1.0.0", &ME, &d.join("work")).unwrap();
        assert!(p.changed);
        assert_eq!(p.branch, "master");
        assert!(p.stat.contains("Tools-reference.md") && p.stat.contains("Changelog.md"), "{}", p.stat);
        // Not pushed yet: the remote still has only the first page.
        assert_eq!(sh(&bare, &["rev-list", "--count", "master"]).trim(), "1");
        push(&p).unwrap();
        assert_eq!(sh(&bare, &["rev-list", "--count", "master"]).trim(), "2");
        assert_eq!(sh(&bare, &["log", "-1", "--format=%s|%ae|%ce", "master"]).trim(), "atlas v1.0.0 wiki|pub@example.invalid|pub@example.invalid");
        let files = sh(&bare, &["ls-tree", "--name-only", "master"]);
        assert_eq!(files.lines().collect::<Vec<_>>(), ["Changelog.md", "Home.md", "Tools-reference.md"]);
        assert_eq!(sh(&bare, &["show", "master:Home.md"]), "# atlas\n\n- [[Tools reference]]\n");

        // A page removed from wiki/ leaves the wiki; an unchanged release commits nothing.
        std::fs::remove_file(src.join("Tools-reference.md")).unwrap();
        stage_pages(&src, "# Changelog\n\n## v1.0.0\n\n- one\n", &pages).unwrap();
        let p = prepare(&pages, &remote, "acme/tool", "v1.0.1", &ME, &d.join("work")).unwrap();
        assert!(p.changed && p.stat.contains("Tools-reference.md"));
        push(&p).unwrap();
        let p = prepare(&pages, &remote, "acme/tool", "v1.0.2", &ME, &d.join("work")).unwrap();
        assert!(!p.changed);
        push(&p).unwrap();
        assert_eq!(sh(&bare, &["rev-list", "--count", "master"]).trim(), "3");
        let _ = std::fs::remove_dir_all(&d);
    }
}
