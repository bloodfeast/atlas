//! DOCS: the wiki (`wiki/`, published to the public repository's wiki by
//! `cargo xtask release`) and the README stay whole and current.
//!
//! * Every `[[Page]]` / `[[text|Page]]` link and every relative or wiki
//!   URL link on a page resolves to a page (a file of `wiki/`, or a page
//!   the release generates).
//! * Every page is reachable from `_Sidebar.md`.
//! * The README's wiki links name existing pages of the public repository
//!   the release publishes to, and its Documentation list names every page.
//! * Every tool in `tools/list` and every configuration key the code
//!   accepts is documented, in backticks, on some page: a key in code that
//!   no page names fails.
//!
//! Links and names inside code (fenced blocks and inline code spans) are
//! not links, as GitHub renders them.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

/// Pages the release writes into the wiki (see `xtask/src/wiki.rs`).
const GENERATED: &[&str] = &["Changelog"];
/// Pages GitHub shows on every page rather than linking to.
const SPECIAL: &[&str] = &["Home", "_Sidebar", "_Footer"];

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn read(p: &Path) -> String {
    std::fs::read_to_string(p).unwrap_or_else(|e| panic!("{}: {e}", p.display())).replace("\r\n", "\n")
}

/// The wiki's pages: file stem to text.
fn pages() -> BTreeMap<String, String> {
    let dir = root().join("wiki");
    let mut out = BTreeMap::new();
    for e in std::fs::read_dir(&dir).expect("wiki/ exists") {
        let p = e.unwrap().path();
        let name = p.file_name().unwrap().to_string_lossy().into_owned();
        let stem = name.strip_suffix(".md").unwrap_or_else(|| panic!("wiki/{name}: only .md pages belong in wiki/"));
        assert!(!GENERATED.contains(&stem), "wiki/{name} is generated by the release; remove it");
        out.insert(stem.to_string(), read(&p));
    }
    out
}

fn page_names(pages: &BTreeMap<String, String>) -> BTreeSet<String> {
    pages.keys().cloned().chain(GENERATED.iter().map(|s| s.to_string())).collect()
}

/// A line cut into `(is_code, text)` runs, CommonMark style: a run of N
/// backticks opens a code span that the next run of exactly N closes; an
/// unclosed run is literal text.
fn spans(l: &str) -> Vec<(bool, String)> {
    let b = l.as_bytes();
    let mut out = Vec::new();
    let (mut i, mut text) = (0, String::new());
    while i < b.len() {
        if b[i] != b'`' {
            let next = l[i..].find('`').map_or(l.len(), |k| i + k);
            text.push_str(&l[i..next]);
            i = next;
            continue;
        }
        let n = b[i..].iter().take_while(|&&c| c == b'`').count();
        let mut j = i + n;
        let mut close = None;
        while j < b.len() {
            if b[j] == b'`' {
                let m = b[j..].iter().take_while(|&&c| c == b'`').count();
                if m == n {
                    close = Some(j);
                    break;
                }
                j += m;
            } else {
                j += 1;
            }
        }
        match close {
            Some(j) => {
                out.push((false, std::mem::take(&mut text)));
                out.push((true, l[i + n..j].to_string()));
                i = j + n;
            }
            None => {
                text.push_str(&l[i..i + n]);
                i += n;
            }
        }
    }
    out.push((false, text));
    out
}

/// The text outside fenced blocks, with inline code spans blanked.
fn prose(text: &str) -> String {
    let mut out = String::new();
    let mut fence = false;
    for l in text.lines() {
        if l.trim_start().starts_with("```") {
            fence = !fence;
        } else if !fence {
            for (code, t) in spans(l) {
                out.push_str(if code { " " } else { &t });
            }
        }
        out.push('\n');
    }
    out
}

/// Every inline code span outside fenced blocks, trimmed.
fn code_spans(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut fence = false;
    for l in text.lines() {
        if l.trim_start().starts_with("```") {
            fence = !fence;
        } else if !fence {
            out.extend(spans(l).into_iter().filter(|(c, _)| *c).map(|(_, t)| t.trim().to_string()));
        }
    }
    out
}

/// The page a link names: `Page Name` and `Page-Name` are the same page.
fn page_of(target: &str) -> String {
    let t = target.split('#').next().unwrap_or("").trim();
    let t = t.strip_suffix(".md").unwrap_or(t);
    t.replace(' ', "-")
}

/// `[[...]]` targets in prose: GitHub wikis read `[[text|Page]]`.
fn wiki_links(prose: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = prose;
    while let Some(a) = rest.find("[[") {
        let after = &rest[a + 2..];
        let Some(b) = after.find("]]") else { break };
        let inner = &after[..b];
        out.push(inner.rsplit('|').next().unwrap_or(inner).to_string());
        rest = &after[b + 2..];
    }
    out
}

/// `[text](target)` targets in prose.
fn md_links(prose: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = prose;
    while let Some(a) = rest.find("](") {
        let after = &rest[a + 2..];
        let Some(b) = after.find(')') else { break };
        out.push(after[..b].trim().to_string());
        rest = &after[b + 1..];
    }
    out
}

/// The public repository the release publishes to (DEFAULT_PUBLIC_REPO).
fn public_repo() -> String {
    let text = read(&root().join("xtask/src/release.rs"));
    let l = text.lines().find(|l| l.starts_with("pub const DEFAULT_PUBLIC_REPO: &str = \"")).expect("DEFAULT_PUBLIC_REPO in release.rs");
    l.split('"').nth(1).unwrap().to_string()
}

/// What a link resolves to, or why it does not: `None` when it is not a
/// wiki link at all (another site, a mail address, an anchor, a file of
/// the repository).
fn wiki_target(link: &str, repo: &str) -> Option<String> {
    let wiki = format!("https://github.com/{repo}/wiki/");
    if let Some(p) = link.strip_prefix(&wiki) {
        return Some(page_of(p));
    }
    if link.contains("://") || link.starts_with("mailto:") || link.starts_with('#') || link.is_empty() {
        return None;
    }
    Some(page_of(link))
}

#[test]
fn every_wiki_link_resolves_and_every_page_is_in_the_sidebar() {
    let pages = pages();
    let names = page_names(&pages);
    let repo = public_repo();
    for s in SPECIAL {
        assert!(pages.contains_key(*s), "wiki/{s}.md is missing");
    }
    let mut bad = Vec::new();
    for (name, text) in &pages {
        let p = prose(text);
        for l in wiki_links(&p) {
            if !names.contains(&page_of(&l)) {
                bad.push(format!("{name}: [[{l}]]"));
            }
        }
        for l in md_links(&p) {
            if let Some(t) = wiki_target(&l, &repo) {
                if !names.contains(&t) {
                    bad.push(format!("{name}: ({l})"));
                }
            }
        }
        assert!(!text.contains('\u{2014}'), "{name}: an em dash");
    }
    assert!(bad.is_empty(), "links to no page:\n{}", bad.join("\n"));

    let sidebar = prose(&pages["_Sidebar"]);
    let listed: BTreeSet<String> = wiki_links(&sidebar).iter().chain(md_links(&sidebar).iter()).filter_map(|l| wiki_target(l, &repo)).collect();
    let orphans: Vec<&String> = names.iter().filter(|n| !SPECIAL[1..].contains(&n.as_str()) && !listed.contains(*n)).collect();
    assert!(orphans.is_empty(), "pages not in _Sidebar.md: {orphans:?}");
}

#[test]
fn the_readme_links_every_page_of_the_public_wiki() {
    let pages = pages();
    let names = page_names(&pages);
    let repo = public_repo();
    let readme = read(&root().join("README.md"));
    let doc = readme.split("\n## Documentation\n").nth(1).expect("README has a Documentation section");
    let doc = doc.split("\n## ").next().unwrap();
    let mut listed = BTreeSet::new();
    for l in md_links(&prose(doc)) {
        let page = l.strip_prefix(&format!("https://github.com/{repo}/wiki/")).unwrap_or_else(|| panic!("README Documentation link {l} is not on the wiki of {repo}"));
        let page = page_of(page);
        assert!(names.contains(&page), "README links the wiki page {page}, which does not exist");
        listed.insert(page);
    }
    let missing: Vec<&String> = names.iter().filter(|n| !SPECIAL.contains(&n.as_str()) && !listed.contains(*n)).collect();
    assert!(missing.is_empty(), "pages the README's Documentation list leaves out: {missing:?}");
    // Every other wiki link in the README, and nothing pointing at another repository's wiki.
    for l in md_links(&prose(&readme)) {
        if l.contains("/wiki") {
            let page = l.strip_prefix(&format!("https://github.com/{repo}/wiki/")).unwrap_or_else(|| panic!("README links another wiki: {l}"));
            assert!(names.contains(&page_of(page)), "README links the missing wiki page {page}");
        }
    }
    let lines = readme.lines().count();
    assert!((120..=260).contains(&lines), "the README is a front page: {lines} lines");
    assert!(readme[..readme.len().min(2000)].contains("You do not need Obsidian"), "the Obsidian note stays near the top");
}

/// Every inline code span on every page.
fn documented() -> BTreeSet<String> {
    pages().values().flat_map(|t| code_spans(t)).map(|s| s.trim().to_string()).collect()
}

#[test]
fn every_tool_is_documented_on_the_wiki() {
    let spans = documented();
    let missing: Vec<String> = atlas::tools::tool_list()
        .iter()
        .map(|t| t.get("name").and_then(|n| n.as_str()).expect("a tool has a name").to_string())
        .filter(|n| !spans.contains(n))
        .collect();
    assert!(missing.is_empty(), "tools in tools/list that no wiki page names in backticks: {missing:?}");
}

/// The source files below `dir`.
fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    for e in std::fs::read_dir(dir).unwrap() {
        let p = e.unwrap().path();
        if p.is_dir() {
            rust_files(&p, out);
        } else if p.extension().is_some_and(|x| x == "rs") {
            out.push(p);
        }
    }
}

/// The string a `let NAME = format!("...")` or `let NAME = "..."` before
/// `at` binds.
fn binding(text: &str, at: usize, name: &str) -> Option<String> {
    let head = &text[..at];
    let i = [format!("let {name} = format!(\""), format!("let {name} = \"")].iter().filter_map(|p| head.rfind(p.as_str()).map(|i| i + p.len())).max()?;
    Some(text[i..].split('"').next()?.to_string())
}

/// `sources[{i}].chunk` -> `sources[].chunk`: every `{...}` dropped.
fn unformat(s: &str) -> String {
    let mut out = String::new();
    let mut depth = 0;
    for c in s.chars() {
        match c {
            '{' => depth += 1,
            '}' => depth -= 1,
            _ if depth == 0 => out.push(c),
            _ => {}
        }
    }
    out
}

/// Every key the configuration parser checks, as its full path:
/// `Fields::new(AT, value, &["k", ...])` gives `AT.k` (`config` is the top).
/// A call whose key list is not written out (the top level and the project
/// entries, which pass a list built from constants) is covered by
/// [`const_keys`]. A label naming `{at}` that is a parameter is expanded
/// for both places a project is read: a `projects` entry (`projects[]`) and
/// the project file `atlas.project.json` (no prefix).
fn config_keys(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut from = 0;
    while let Some(i) = text[from..].find("Fields::new(") {
        let at = from + i;
        let args = &text[at + "Fields::new(".len()..];
        from = at + 1;
        if args.starts_with("at: &str") {
            continue; // the definition
        }
        let Some(list) = args.find("&[") else { continue };
        let first_line_end = args.find('\n').unwrap_or(args.len());
        if list > first_line_end {
            continue; // the key list is a variable
        }
        let label = if let Some(r) = args.strip_prefix('"') {
            r.split('"').next().unwrap().to_string()
        } else if let Some(r) = args.strip_prefix("&format!(\"") {
            r.split('"').next().unwrap().to_string()
        } else if let Some(r) = args.strip_prefix('&') {
            let name: String = r.chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
            binding(text, at, &name).unwrap_or_else(|| panic!("Fields::new(&{name}, ...): cannot find what {name} names"))
        } else {
            continue; // a parameter with a variable key list
        };
        let labels: Vec<String> = if !label.contains("{at}") {
            vec![label]
        } else if let Some(b) = binding(text, at, "at") {
            vec![label.replace("{at}", &b)]
        } else {
            vec![label.replace("{at}", "projects[]"), label.replacen("{at}.", "", 1)]
        };
        let keys = &args[list + 2..];
        let keys = &keys[..keys.find(']').unwrap()];
        for label in labels {
            let label = unformat(&label);
            for k in keys.split('"').skip(1).step_by(2) {
                out.push(if label == "config" { k.to_string() } else { format!("{label}.{k}") });
            }
        }
    }
    out
}

/// The key-list constants the variable calls are built from: the top level
/// (`TOP_KEYS`, `USER_KEYS`), a `projects` entry (`ENTRY_KEYS`) and the
/// project file (`FILE_KEYS`).
fn const_keys(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    for (name, prefix) in [("TOP_KEYS", ""), ("USER_KEYS", ""), ("ENTRY_KEYS", "projects[]."), ("FILE_KEYS", "")] {
        let Some(i) = text.find(&format!("const {name}: &[&str] =")) else { continue };
        let rest = &text[i + format!("const {name}: &[&str] =").len()..];
        let rest = &rest[rest.find("&[").unwrap() + 2..];
        let rest = &rest[..rest.find(']').unwrap()];
        out.extend(rest.split('"').skip(1).step_by(2).map(|k| format!("{prefix}{k}")));
    }
    out
}

/// The `lean.*` keys the code reads, from the backticked names in its docs.
fn lean_keys(text: &str) -> Vec<String> {
    text.split('`')
        .skip(1)
        .step_by(2)
        .filter(|s| s.starts_with("lean.") && !s.ends_with('.') && s.chars().all(|c| c.is_ascii_lowercase() || c == '.' || c == '_'))
        .map(str::to_string)
        .collect()
}

#[test]
fn every_configuration_key_in_code_is_documented_on_the_wiki() {
    let spans = documented();
    let mut files = Vec::new();
    rust_files(&root().join("src"), &mut files);
    let mut keys = BTreeSet::new();
    for f in &files {
        let text = read(f);
        keys.extend(config_keys(&text));
        keys.extend(const_keys(&text));
        keys.extend(lean_keys(&text));
    }
    for k in ["db", "projects", "projects[].roots", "repos[].talks_to", "user.memory", "memory.tree.branches[].repo", "vaults[].path", "memory.tree.hub_max", "code.roots[].build_scripts", "sources[].chunk.max_level", "lean.handles.slice_bytes"] {
        assert!(keys.contains(k), "the key reader no longer sees {k}: {keys:?}");
    }
    let missing: Vec<&String> = keys.iter().filter(|k| !spans.contains(*k)).collect();
    assert!(missing.is_empty(), "configuration keys no wiki page names in backticks (add them to Configuration-reference.md): {missing:?}");
}

#[test]
fn the_link_readers_read_what_github_renders() {
    let p = prose("see [[Code index]] and [[the store|SQLite store]], [x](Security-model#threat-model)\n`[[not a link]]`\n```\n[[nor this]]\n```\n");
    assert_eq!(wiki_links(&p), ["Code index", "SQLite store"]);
    assert_eq!(wiki_links(&prose("markup (`*` `` ` `` `~`): `- [[A B]]` cites")), Vec::<String>::new());
    assert_eq!(code_spans("a `x` and `` y`z `` and ` unclosed"), ["x", "y`z"]);
    assert_eq!(md_links(&p), ["Security-model#threat-model"]);
    assert_eq!(page_of("Security-model#threat-model"), "Security-model");
    assert_eq!(wiki_target("https://github.com/o/r/wiki/Code-index", "o/r").as_deref(), Some("Code-index"));
    assert_eq!(wiki_target("https://example.com/x", "o/r"), None);
    let k = config_keys("let at = format!(\"sources[{i}]\");\nlet f = Fields::new(&at, x, &[\"name\", \"root\"])?;\nFields::new(&format!(\"{at}.chunk\"), v, &[\"max_level\"]);\nFields::new(\"config\", &v, &[\"db\"]);");
    assert_eq!(k, ["sources[].name", "sources[].root", "sources[].chunk.max_level", "db"]);
}
