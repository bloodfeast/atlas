fn tokens(s: &str) -> impl Iterator<Item = String> + '_ {
    s.split(|c: char| !c.is_alphanumeric()).filter(|w| w.len() >= 3 && !w.chars().all(|c| c.is_ascii_digit())).map(str::to_lowercase).filter(|w| !STOP.contains(&w.as_str()))
}

/// Words that never name a part by default: they say nothing about a topic.
pub const NAME_STOP: &[&str] = &["requested", "agents", "agent", "work", "fact", "facts", "note", "notes", "memory", "memories"];

/// A memory's naming words: those of its file name (a curated subject),
/// then of its description.
fn leaf_words(l: &Leaf, stop: &[String]) -> (BTreeSet<String>, BTreeSet<String>) {
    let ok = |w: &String| !stop.contains(w);
    (tokens(&l.stem).filter(ok).collect(), tokens(&l.stem).chain(tokens(&l.description)).filter(ok).collect())
}

fn hit(hay: &str, w: &str) -> bool {
    match w.strip_suffix('*') {
        Some(p) => {
            let b = hay.as_bytes();
            let mut from = 0;
            while let Some(i) = hay[from..].find(p) {
                let s = from + i;
                if s == 0 || !b[s - 1].is_ascii_alphanumeric() {
                    return true;
                }
                from = s + 1;
                while from < hay.len() && !hay.is_char_boundary(from) {
                    from += 1;
                }
            }
            false
        }
        None => super::contains_word(hay, w),
    }
}

/// A memory's score for a branch from its words and type (see
/// [`BranchSpec::words`]).
pub fn score(b: &BranchSpec, l: &Leaf) -> usize {
    let slug = l.stem.replace(['-', '_'], " ").to_lowercase();
    let desc = l.description.to_lowercase();
    let mut s = 0;
    for w in &b.words {
        if hit(&slug, w) {
            s += 3;
        } else if hit(&desc, w) {
            s += 1;
        }
    }
    if b.types.iter().any(|t| t == &l.kind) {
        s += 2;
    }
    s
}

/// Vectors standing in for a model: hashed word counts, unit length.
/// Deterministic, so a tree built without a model rebuilds the same.
pub fn lexical_vectors(texts: &[String]) -> Vec<Vec<f32>> {
    const DIM: usize = 512;
    texts
        .iter()
        .map(|t| {
            let mut v = vec![0f32; DIM];
            for w in tokens(t) {
                let mut h: u64 = 0xcbf2_9ce4_8422_2325;
                for b in w.bytes() {
                    h ^= u64::from(b);
                    h = h.wrapping_mul(0x0100_0000_01b3);
                }
                v[(h % DIM as u64) as usize] += 1.0;
            }
            normalize(&mut v);
            v
        })
        .collect()
}

fn normalize(v: &mut [f32]) {
    let n = v.iter().map(|x| x * x).sum::<f32>().sqrt();
    if n > 0.0 {
        for x in v.iter_mut() {
            *x /= n;
        }
    }
}

fn dot(a: &[f32], b: &[f32]) -> f32 {
    a.iter().zip(b).map(|(x, y)| x * y).sum()
}

fn mean(vs: &[&Vec<f32>]) -> Vec<f32> {
    let dim = vs.first().map_or(0, |v| v.len());
    let mut m = vec![0f32; dim];
    for v in vs {
        for (a, b) in m.iter_mut().zip(v.iter()) {
            *a += b;
        }
    }
    normalize(&mut m);
    m
}

/// The text a memory is embedded from.
pub fn embed_text(l: &Leaf) -> String {
    let body: String = l.body.split_whitespace().collect::<Vec<_>>().join(" ").chars().take(600).collect();
    format!("{}. {}. {body}", l.stem.replace(['-', '_'], " "), l.description)
}

/// The members a memory is compared with when it is placed by meaning.
const NEAREST: usize = 5;

/// Embeds texts (a model's `embed_many`, or [`lexical_vectors`]).
pub type Embed<'a> = dyn FnMut(&[String]) -> Vec<Vec<f32>> + Send + 'a;

struct Vecs<'a, 'b> {
    by_stem: &'a HashMap<String, &'a Leaf>,
    cache: HashMap<String, Vec<f32>>,
    embed: &'a mut Embed<'b>,
}

impl Vecs<'_, '_> {
    fn ensure(&mut self, stems: &[String]) {
        let need: Vec<&String> = stems.iter().filter(|s| !self.cache.contains_key(*s) && self.by_stem.contains_key(*s)).collect();
        if need.is_empty() {
            return;
        }
        let texts: Vec<String> = need.iter().map(|s| embed_text(self.by_stem[*s])).collect();
        let out = (self.embed)(&texts);
        for (s, mut v) in need.into_iter().zip(out) {
            normalize(&mut v);
            self.cache.insert(s.clone(), v);
        }
    }

    fn centroid(&mut self, stems: &[String]) -> Vec<f32> {
        self.ensure(stems);
        let vs: Vec<&Vec<f32>> = stems.iter().filter_map(|s| self.cache.get(s)).collect();
        mean(&vs)
    }
}

/// Spherical k-means with a size cap per cluster, seeded farthest-first:
/// deterministic for given vectors.
fn kmeans(v: &[Vec<f32>], k: usize, cap: usize) -> Vec<usize> {
    let n = v.len();
    let all: Vec<&Vec<f32>> = v.iter().collect();
    let m = mean(&all);
    let mut seeds = vec![(0..n).min_by(|&a, &b| dot(&v[a], &m).total_cmp(&dot(&v[b], &m)).then(a.cmp(&b))).unwrap_or(0)];
    while seeds.len() < k {
        let next = (0..n)
            .filter(|i| !seeds.contains(i))
            .min_by(|&a, &b| {
                let fa = seeds.iter().map(|&s| dot(&v[a], &v[s])).fold(f32::MIN, f32::max);
                let fb = seeds.iter().map(|&s| dot(&v[b], &v[s])).fold(f32::MIN, f32::max);
                fa.total_cmp(&fb).then(a.cmp(&b))
            })
            .unwrap_or(0);
        seeds.push(next);
    }
    let mut cent: Vec<Vec<f32>> = seeds.iter().map(|&s| v[s].clone()).collect();
    let mut asg = vec![usize::MAX; n];
    for _ in 0..30 {
        let mut pairs: Vec<(f32, usize, usize)> = Vec::with_capacity(n * k);
        for (i, x) in v.iter().enumerate() {
            for (c, y) in cent.iter().enumerate() {
                pairs.push((dot(x, y), i, c));
            }
        }
        pairs.sort_by(|a, b| b.0.total_cmp(&a.0).then(a.1.cmp(&b.1)).then(a.2.cmp(&b.2)));
        let mut count = vec![0usize; k];
        let mut next = vec![usize::MAX; n];
        for (_, i, c) in pairs {
            if next[i] == usize::MAX && count[c] < cap {
                next[i] = c;
                count[c] += 1;
            }
        }
        if next == asg {
            break;
        }
        asg = next;
        for (c, slot) in cent.iter_mut().enumerate() {
            let members: Vec<&Vec<f32>> = (0..n).filter(|&i| asg[i] == c).map(|i| &v[i]).collect();
            if !members.is_empty() {
                *slot = mean(&members);
            }
        }
    }
    asg
}

/// Words that set a group of memories apart from the rest of its branch,
/// most distinctive first.
fn distinctive(group: &[String], all: &[String], words: &HashMap<String, (BTreeSet<String>, BTreeSet<String>)>, skip: &HashSet<String>, n: usize) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for slug in [true, false] {
        for w in distinctive_in(group, all, words, slug, skip, n) {
            // One of a singular and its plural.
            let dup = out.iter().any(|o| *o == w || format!("{o}s") == w || format!("{w}s") == *o);
            if out.len() < n && !dup {
                out.push(w);
            }
        }
    }
    out
}

fn distinctive_in(group: &[String], all: &[String], words: &HashMap<String, (BTreeSet<String>, BTreeSet<String>)>, slug: bool, skip: &HashSet<String>, n: usize) -> Vec<String> {
    let df = |set: &[String]| {
        let mut m: BTreeMap<&str, usize> = BTreeMap::new();
        for s in set {
            for w in words.get(s).map(|p| if slug { &p.0 } else { &p.1 }).into_iter().flatten() {
                *m.entry(w.as_str()).or_default() += 1;
            }
        }
        m
    };
    let (g, a) = (df(group), df(all));
    let (ng, rest) = (group.len().max(1) as f64, (all.len().saturating_sub(group.len())).max(1) as f64);
    let mut scored: Vec<(f64, usize, &str)> = g
        .iter()
        .filter(|(w, c)| !skip.contains(**w) && (**c >= 2 || group.len() < 2))
        .map(|(w, &c)| (c as f64 / ng - (a.get(w).copied().unwrap_or(0).saturating_sub(c)) as f64 / rest, c, *w))
        .collect();
    scored.sort_by(|x, y| y.0.total_cmp(&x.0).then(y.1.cmp(&x.1)).then(x.2.cmp(y.2)));
    scored.into_iter().take(n * 2).map(|(_, _, w)| w.to_string()).collect()
}

/// What a rebuild did.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Churn {
    /// Files written (relative to the memory folder, `/`-separated).
    pub written: Vec<String>,
    /// Generated hub files deleted.
    pub deleted: Vec<String>,
    /// Memories new to the tree.
    pub added: Vec<String>,
    /// Memories gone from the folder.
    pub removed: Vec<String>,
    /// Memories that changed branch (a `branch:` flag).
    pub moved: Vec<String>,
    /// Hubs split, and hubs merged away.
    pub splits: usize,
    /// Hubs merged into a sibling.
    pub merges: usize,
    /// Where a hand-written root was saved before its first rewrite.
    pub backup: Option<String>,
}

impl Churn {
    /// Whether the rebuild changed any file.
    pub fn changed(&self) -> bool {
        !self.written.is_empty() || !self.deleted.is_empty()
    }

    /// One line.
    pub fn line(&self) -> String {
        format!(
            "{} files written, {} deleted; memories {} added, {} removed, {} moved; {} splits, {} merges",
            self.written.len(),
            self.deleted.len(),
            self.added.len(),
            self.removed.len(),
            self.moved.len(),
            self.splits,
            self.merges
        )
    }
}

crate::impl_to_json!(Churn { written, deleted, added, removed, moved, splits, merges, backup });

/// A built tree: every file's text, ready to compare and write.
#[derive(Debug, Clone, Default)]
pub struct Built {
    /// Path (relative to the memory folder, `/`-separated) to text.
    pub files: BTreeMap<String, String>,
    /// The branches, as `(branch index, hub)`; empty ones left out.
    pub branches: Vec<(usize, Hub)>,
    /// Each memory's line.
    pub lines: BTreeMap<String, String>,
    /// As [`Churn`]: memories added, removed and moved; splits and merges.
    pub churn: Churn,
}

/// Builds the tree for the memories in `leaves` from the tree on disk.
///
/// # Arguments
///
/// * `spec` - the settings.
/// * `index` - the root's file name.
/// * `disk` - the tree as the files hold it ([`load`]).
/// * `leaves` - the memory files ([`read_leaves`]).
/// * `embed` - embeds texts; called only for memories that need placing by
///   meaning and for branches being split or merged.
pub fn build(spec: &TreeSpec, index: &str, disk: &Loaded, leaves: &[Leaf], embed: &mut Embed<'_>) -> Built {
    let by_stem: HashMap<String, &Leaf> = leaves.iter().map(|l| (l.stem.clone(), l)).collect();
    let words: HashMap<String, (BTreeSet<String>, BTreeSet<String>)> = leaves.iter().map(|l| (l.stem.clone(), leaf_words(l, &spec.name_stop))).collect();
    let mut churn = Churn::default();
    // Lines: the root's (a writer's), else the hub's, else the frontmatter's.
    let mut lines: BTreeMap<String, String> = BTreeMap::new();
    let root_lines: HashMap<&str, &str> = disk.root_lines.iter().map(|(s, l)| (s.as_str(), l.as_str())).collect();
    for l in leaves {
        let base = root_lines.get(l.stem.as_str()).map(|s| s.to_string()).or_else(|| disk.hub_lines.get(&l.stem).cloned()).unwrap_or_else(|| synth_line(l, spec.line_max));
        // The hook is the memory's description; an index line (often cut
        // short, or merged by hand) gives only the title, or the whole line
        // when the file has no description.
        let d = l.description.trim();
        let line = if d.is_empty() { base } else { format!("- [{}]({}.md) - {d}", title_of(&base), l.stem) };
        // A `slug` line is cut when rendered: the line read back from it is
        // longer than it, and cutting that again would shorten it each rebuild.
        lines.insert(l.stem.clone(), if spec.format == LineFormat::Link { cap_line(&line, spec.line_max) } else { line });
    }
    let override_of = |l: &Leaf| l.branch.as_ref().and_then(|b| spec.branches.iter().position(|x| &x.name == b));
    // The tree as it was, less what left or was moved by a flag.
    let mut tree: Vec<Hub> = spec.branches.iter().map(|b| Hub { file: format!("{}.md", b.name), ..Hub::default() }).collect();
    let mut placed: HashSet<String> = HashSet::new();
    let mut was_in: HashMap<String, usize> = HashMap::new();
    for (name, hub) in &disk.branches {
        let Some(bi) = spec.branches.iter().position(|b| &b.name == name) else { continue };
        if !tree[bi].leaves.is_empty() || !tree[bi].subs.is_empty() {
            continue;
        }
        let mut keep = |stems: &[String]| -> Vec<String> {
            let mut out = Vec::new();
            for s in stems {
                if let Some(l) = by_stem.get(s) {
                    was_in.entry(s.clone()).or_insert(bi);
                    if override_of(l).is_none_or(|o| o == bi) && placed.insert(s.clone()) {
                        out.push(s.clone());
                    }
                } else if !churn.removed.contains(s) {
                    churn.removed.push(s.clone());
                }
            }
            out
        };
        tree[bi].leaves = keep(&hub.leaves);
        for sub in &hub.subs {
            let kept = keep(&sub.leaves);
            tree[bi].subs.push(Hub { file: sub.file.clone(), leaves: kept, subs: Vec::new(), title: sub.title.clone() });
        }
    }
    let mut vecs = Vecs { by_stem: &by_stem, cache: HashMap::new(), embed };
    // Place what is not in the tree. A `branch:` flag decides. Otherwise
    // every branch scores the memory by meaning (its cosine with the
    // branch's centroid) plus its words (the keyword score over the
    // memory's best one, times `keyword_weight`). A centroid is made of the
    // branch's listed memories and of those its words claim confidently (a
    // score of 3 or more, at least twice the runner-up's).
    let mut place: Vec<(usize, &Leaf)> = Vec::new();
    let mut open: Vec<&Leaf> = Vec::new();
    for l in leaves.iter().filter(|l| !placed.contains(&l.stem)) {
        match override_of(l) {
            Some(b) => place.push((b, l)),
            None => open.push(l),
        }
    }
    if !open.is_empty() {
        let kw: Vec<Vec<usize>> = open.iter().map(|l| spec.branches.iter().map(|b| score(b, l)).collect()).collect();
        let mut members: Vec<Vec<String>> = tree.iter().map(Hub::all).collect();
        for (b, l) in &place {
            members[*b].push(l.stem.clone());
        }
        for (i, l) in open.iter().enumerate() {
            let mut s: Vec<(usize, usize)> = kw[i].iter().copied().enumerate().map(|(b, x)| (x, b)).collect();
            s.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(&b.1)));
            let (best, second) = (s[0].0, s.get(1).map_or(0, |x| x.0));
            if best >= 3 && best >= 2 * second.max(1) {
                members[s[0].1].push(l.stem.clone());
            }
        }
        let mut cents: Vec<Vec<f32>> = Vec::new();
        for (i, m) in members.iter().enumerate() {
            if m.is_empty() {
                let b = &spec.branches[i];
                let t = format!("{}. {}. {}", b.title, b.hook, b.words.join(" ").replace('*', ""));
                let mut v = (vecs.embed)(&[t]).pop().unwrap_or_default();
                normalize(&mut v);
                cents.push(v);
            } else {
                cents.push(vecs.centroid(m));
            }
        }
        let stems: Vec<String> = open.iter().map(|l| l.stem.clone()).collect();
        vecs.ensure(&stems);
        let w = spec.keyword_weight as f32 / 1000.0;
        for (i, l) in open.iter().enumerate() {
            let v = vecs.cache.get(&l.stem).cloned().unwrap_or_default();
            let top = kw[i].iter().copied().max().unwrap_or(0) as f32;
            // Meaning: the mean cosine with the branch's nearest members (a
            // branch spans several topics, which one centroid blurs), the
            // centroid for a branch with too few.
            let near = |b: usize| -> f32 {
                let mut c: Vec<f32> = members[b].iter().filter(|m| **m != l.stem).filter_map(|m| vecs.cache.get(m)).map(|x| dot(&v, x)).collect();
                if c.len() < NEAREST {
                    return dot(&v, &cents[b]);
                }
                c.sort_by(|x, y| y.total_cmp(x));
                c[..NEAREST].iter().sum::<f32>() / NEAREST as f32
            };
            let total = |b: usize| near(b) + if top > 0.0 { w * kw[i][b] as f32 / top } else { 0.0 };
            let bi = (0..cents.len()).max_by(|&a, &b| total(a).total_cmp(&total(b)).then(b.cmp(&a))).unwrap_or(0);
            place.push((bi, *l));
        }
    }
    place.sort_by(|a, b| a.1.stem.cmp(&b.1.stem));
    for (bi, l) in place {
        match was_in.get(&l.stem) {
            Some(&old) if old != bi => churn.moved.push(l.stem.clone()),
            Some(_) => {}
            None => churn.added.push(l.stem.clone()),
        }
        let hub = &mut tree[bi];
        if hub.subs.is_empty() {
            hub.leaves.push(l.stem.clone());
        } else {
            let mut best = (f32::MIN, 0usize);
            vecs.ensure(std::slice::from_ref(&l.stem));
            let v = vecs.cache.get(&l.stem).cloned().unwrap_or_default();
            for (si, s) in hub.subs.clone().iter().enumerate() {
                let d = if s.leaves.is_empty() { f32::MIN / 2.0 } else { dot(&v, &vecs.centroid(&s.leaves)) };
                if d > best.0 {
                    best = (d, si);
                }
            }
            hub.subs[best.1].leaves.push(l.stem.clone());
        }
    }
    // Rebalance: split what is over, merge what is under, collapse a branch
    // left with one part.
    let mut used: BTreeSet<String> = disk.hub_files.clone();
    // A part named like a memory would be ambiguous in the `slug` format.
    used.extend(leaves.iter().map(|l| format!("{}.md", l.stem)));
    for (bi, hub) in tree.iter_mut().enumerate() {
        let name = &spec.branches[bi].name;
        used.insert(hub.file.clone());
        for s in &hub.subs {
            used.insert(s.file.clone());
        }
        let all = hub.all();
        let skip: HashSet<String> = tokens(&spec.branches[bi].title).chain(tokens(name)).collect();
        let new_name = |group: &[String], used: &mut BTreeSet<String>| -> String {
            let w = distinctive(group, &all, &words, &skip, 2);
            let mut cands: Vec<String> = Vec::new();
            if let Some(a) = w.first() {
                cands.push(format!("{name}-{a}.md"));
                if let Some(b) = w.get(1) {
                    cands.push(format!("{name}-{a}-{b}.md"));
                }
            }
            let f = cands.into_iter().find(|c| !used.contains(c)).unwrap_or_else(|| (2..).map(|i| format!("{name}-{i}.md")).find(|c| !used.contains(c)).unwrap_or_default());
            used.insert(f.clone());
            f
        };
        let split = |stems: &[String], vecs: &mut Vecs<'_, '_>| -> Vec<Vec<String>> {
            let mut stems = stems.to_vec();
            stems.sort();
            let k = stems.len().div_ceil(spec.hub_target).max(2);
            let even = stems.len().div_ceil(k);
            let cap = (even + even / 3).max(even).min(spec.hub_max);
            vecs.ensure(&stems);
            let v: Vec<Vec<f32>> = stems.iter().map(|s| vecs.cache.get(s).cloned().unwrap_or_default()).collect();
            let asg = kmeans(&v, k, cap);
            let mut groups: Vec<Vec<String>> = vec![Vec::new(); k];
            for (i, s) in stems.into_iter().enumerate() {
                groups[asg[i].min(k - 1)].push(s);
            }
            groups.retain(|g| !g.is_empty());
            groups.sort_by(|a, b| b.len().cmp(&a.len()).then(a[0].cmp(&b[0])));
            groups
        };
        if hub.subs.is_empty() && hub.leaves.len() > spec.hub_max {
            churn.splits += 1;
            for g in split(&hub.leaves, &mut vecs) {
                let file = new_name(&g, &mut used);
                hub.subs.push(Hub { file, leaves: g, subs: Vec::new(), title: None });
            }
            hub.leaves.clear();
        }
        if hub.subs.is_empty() {
            continue;
        }
        hub.subs.retain(|s| !s.leaves.is_empty());
        let mut i = 0;
        while i < hub.subs.len() {
            if hub.subs[i].leaves.len() > spec.hub_max {
                churn.splits += 1;
                let groups = split(&hub.subs[i].leaves, &mut vecs);
                let mut it = groups.into_iter();
                hub.subs[i].leaves = it.next().unwrap_or_default();
                hub.subs[i].title = None;
                let mut at = i + 1;
                for g in it {
                    let file = new_name(&g, &mut used);
                    hub.subs.insert(at, Hub { file, leaves: g, subs: Vec::new(), title: None });
                    at += 1;
                }
                i = at;
            } else {
                i += 1;
            }
        }
        loop {
            if hub.subs.len() < 2 {
                break;
            }
            let Some(small) = (0..hub.subs.len()).filter(|&i| hub.subs[i].leaves.len() < spec.hub_min).min_by(|&a, &b| hub.subs[a].leaves.len().cmp(&hub.subs[b].leaves.len()).then(hub.subs[a].file.cmp(&hub.subs[b].file))) else {
                break;
            };
            let c = vecs.centroid(&hub.subs[small].leaves.clone());
            let target = (0..hub.subs.len())
                .filter(|&j| j != small && hub.subs[j].leaves.len() + hub.subs[small].leaves.len() <= spec.hub_max)
                .map(|j| {
                    let cj = vecs.centroid(&hub.subs[j].leaves.clone());
                    (dot(&c, &cj), j)
                })
                .max_by(|a, b| a.0.total_cmp(&b.0).then(b.1.cmp(&a.1)));
            let Some((_, j)) = target else { break };
            churn.merges += 1;
            let moved = std::mem::take(&mut hub.subs[small].leaves);
            hub.subs[j].leaves.extend(moved);
            hub.subs[j].title = None;
            hub.subs.remove(small);
        }
        if hub.subs.len() == 1 {
            churn.merges += 1;
            hub.leaves = hub.subs.remove(0).leaves;
        }
    }
    for hub in &mut tree {
        hub.leaves.sort();
        for s in &mut hub.subs {
            s.leaves.sort();
        }
    }
    let branches: Vec<(usize, Hub)> = tree.into_iter().enumerate().filter(|(_, h)| !h.leaves.is_empty() || !h.subs.is_empty()).collect();
    let files = render(spec, index, &branches, &lines, leaves, &words);
    Built { files, branches, lines, churn }
}

fn title_of(line: &str) -> &str {
    link(line).map_or(line, |(t, _, _)| t)
}

/// A part's label (`Words, words, words`) and hook (its count and a few of
/// its memories' titles, those that carry a label word first).
fn sub_title(spec: &TreeSpec, bi: usize, hub: &Hub, all: &[String], words: &HashMap<String, (BTreeSet<String>, BTreeSet<String>)>, lines: &BTreeMap<String, String>) -> (String, String) {
    let b = &spec.branches[bi];
    let title = hub.title.clone().unwrap_or_else(|| {
        let skip: HashSet<String> = tokens(&b.title).chain(tokens(&b.name)).collect();
        let w = distinctive(&hub.leaves, all, words, &skip, 3);
        let mut t = w.join(", ");
        if let Some(c) = t.get(..1) {
            t = c.to_uppercase() + &t[1..];
        }
        if t.is_empty() {
            b.title.clone()
        } else {
            t
        }
    });
    let label: Vec<String> = tokens(&title).collect();
    let mut picks: Vec<&String> = hub.leaves.iter().filter(|s| tokens(s).any(|w| label.contains(&w))).collect();
    picks.extend(hub.leaves.iter().filter(|s| !tokens(s).any(|w| label.contains(&w))));
    // A `slug` file keeps no titles, so its examples are slugs.
    let ex: Vec<&str> = picks.into_iter().take(4).map(|s| if spec.format == LineFormat::Link { title_of(&lines[s]) } else { s.as_str() }).collect();
    (title, format!("{} memories: {}", hub.leaves.len(), ex.join("; ")))
}

fn hub_link(spec: &TreeSpec, title: &str, target: &str, hook: &str) -> String {
    match spec.format {
        LineFormat::Link => cap_line(&format!("- [{title}]({target}) - {hook}"), spec.line_max),
        LineFormat::Slug => {
            let slug = target.rsplit('/').next().unwrap_or(target).trim_end_matches(".md");
            cap_line(&format!("- {slug}: {title} - {hook}"), spec.line_max)
        }
    }
}

fn leaf_line(spec: &TreeSpec, stem: &str, line: &str, prefix: &str) -> String {
    match (spec.format, link(line)) {
        (LineFormat::Slug, _) => {
            let h = hook_of(line);
            cap_line(&if h.is_empty() { format!("- {stem}") } else { format!("- {stem}: {h}") }, spec.line_max)
        }
        (LineFormat::Link, Some((title, target, rest))) => format!("- [{title}]({prefix}{target}){rest}"),
        (LineFormat::Link, None) => line.to_string(),
    }
}

fn render(spec: &TreeSpec, index: &str, branches: &[(usize, Hub)], lines: &BTreeMap<String, String>, leaves: &[Leaf], words: &HashMap<String, (BTreeSet<String>, BTreeSet<String>)>) -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();
    let dir = &spec.hub_dir;
    let mut root = format!("# Memory index\n{MARKER} on every rescan: edit a memory file, not this index. A line added here that links a new memory file is filed into a branch on the next rescan.\n");
    if spec.format == LineFormat::Slug {
        root.push_str(&format!("Each line is `- slug: hook`: a memory is `slug.md` in this folder; a branch or hub is `{dir}/slug.md`.\n"));
    }
    root.push_str("## Branches (read one to find a memory)\n");
    for (bi, hub) in branches {
        let b = &spec.branches[*bi];
        root.push_str(&hub_link(spec, &b.title, &format!("{dir}/{}", hub.file), &b.hook));
        root.push('\n');
        let mut text = format!("# {}\n{MARKER}; part of the memory index (../{index}). One line per memory, or per smaller hub.\n\n", b.title);
        if hub.subs.is_empty() {
            for s in &hub.leaves {
                text.push_str(&leaf_line(spec, s, &lines[s], "../"));
                text.push('\n');
            }
        } else {
            let all = hub.all();
            for sub in &hub.subs {
                let (title, hook) = sub_title(spec, *bi, sub, &all, words, lines);
                text.push_str(&hub_link(spec, &title, &sub.file, &hook));
                text.push('\n');
                let mut st = format!("# {title}\n{MARKER}; part of the memory index (../{index}), under {}.md. One line per memory.\n\n", b.name);
                for s in &sub.leaves {
                    st.push_str(&leaf_line(spec, s, &lines[s], "../"));
                    st.push('\n');
                }
                files.insert(format!("{dir}/{}", sub.file), st);
            }
        }
        files.insert(format!("{dir}/{}", hub.file), text);
    }
    let pins: Vec<&Leaf> = leaves.iter().filter(|l| l.pinned).collect();
    if !pins.is_empty() {
        root.push_str("## Pinned (also in their branches)\n");
        for l in pins {
            root.push_str(&leaf_line(spec, &l.stem, &lines[&l.stem], ""));
            root.push('\n');
            let body = l.body.split_whitespace().collect::<Vec<_>>().join(" ");
            if !body.is_empty() && body.chars().count() <= spec.pin_body_chars {
                root.push_str("  ");
                root.push_str(&body);
                root.push('\n');
            }
        }
    }
    files.insert(index.to_string(), root);
    files
}

fn rel_path(dir: &Path, rel: &str) -> PathBuf {
    rel.split('/').fold(dir.to_path_buf(), |p, c| p.join(c))
}

/// Rebuilds the tree in a memory folder: reads the memory files and the
/// tree, builds, and (when `write`) writes the files whose bytes changed and
/// deletes generated hub files no longer used. A root that atlas did not
/// generate is first copied to `HUB_DIR/INDEX.before-tree` (once).
///
/// # Errors
///
/// [`Error::Io`] for a file that cannot be read or written.
pub fn rebuild(dir: &Path, index: &str, spec: &TreeSpec, embed: &mut Embed<'_>, write: bool) -> Result<(Churn, Built)> {
    let leaves = read_leaves_pinned(dir, index, spec)?;
    let disk = load(dir, index, spec)?;
    let mut built = build(spec, index, &disk, &leaves, embed);
    let shared = shared_section(spec, &shared_pins(dir, index, spec));
    if let (false, Some(root)) = (shared.is_empty(), built.files.get_mut(index)) {
        root.push_str(&shared);
    }
    let mut churn = built.churn.clone();
    for (rel, text) in &built.files {
        let p = rel_path(dir, rel);
        if std::fs::read(&p).ok().as_deref() == Some(text.as_bytes()) {
            continue;
        }
        churn.written.push(rel.clone());
    }
    for f in &disk.hub_files {
        let rel = format!("{}/{f}", spec.hub_dir);
        if !built.files.contains_key(&rel) {
            churn.deleted.push(rel);
        }
    }
    if write {
        if let (Some(root), false) = (&disk.root, disk.generated) {
            let rel = format!("{}/{index}.before-tree", spec.hub_dir);
            let p = rel_path(dir, &rel);
            if !p.exists() && churn.written.iter().any(|w| w == index) {
                if let Some(d) = p.parent() {
                    std::fs::create_dir_all(d)?;
                }
                std::fs::write(&p, root)?;
                churn.backup = Some(rel);
            }
        }
        for rel in &churn.written {
            let p = rel_path(dir, rel);
            if let Some(d) = p.parent() {
                std::fs::create_dir_all(d)?;
            }
            let mut tmp = p.as_os_str().to_owned();
            tmp.push(format!(".atlas-tmp-{}", std::process::id()));
            let tmp = PathBuf::from(tmp);
            std::fs::write(&tmp, built.files[rel].as_bytes())?;
            std::fs::rename(&tmp, &p).inspect_err(|_| {
                let _ = std::fs::remove_file(&tmp);
            })?;
        }
        for rel in &churn.deleted {
            std::fs::remove_file(rel_path(dir, rel))?;
        }
    }
    Ok((churn, built))
}

/// The index a sync reads in place of a generated root: every memory's
/// line in tree order (branch, hub, memory), then root lines that link a
/// memory no hub lists yet. `None` when the root is not generated (the sync
/// reads the root itself).
///
/// # Errors
///
/// As [`load`].
pub fn flat_index(dir: &Path, index: &str, spec: &TreeSpec) -> Result<Option<String>> {
    let disk = load(dir, index, spec)?;
    if !disk.generated {
        return Ok(None);
    }
    let mut out = String::new();
    let mut seen: HashSet<&str> = HashSet::new();
    for (_, hub) in &disk.branches {
        let mut stems: Vec<&String> = hub.leaves.iter().collect();
        for s in &hub.subs {
            stems.extend(s.leaves.iter());
        }
        for s in stems {
            if let (Some(l), true) = (disk.hub_lines.get(s), seen.insert(s.as_str())) {
                out.push_str(l);
                out.push('\n');
            }
        }
    }
    for (s, l) in &disk.root_lines {
        if seen.insert(s.as_str()) {
            out.push_str(l);
            out.push('\n');
        }
    }
    Ok(Some(out))
}

/// The navigation check: what a reader following links from the root finds.
#[derive(Debug, Clone, Default)]
pub struct Nav {
    /// Memory files in the folder.
    pub leaves: usize,
    /// Hub files reached.
    pub hubs: usize,
    /// Lines in the root.
    pub root_lines: usize,
    /// Bytes of the root.
    pub root_bytes: usize,
    /// Reads (files opened after the root) to each memory file, the file
    /// itself included: index 1 to 3, then more.
    pub reads: [usize; 5],
    /// The most lines any hub lists.
    pub fanout_max: usize,
    /// Mean bytes of the root plus the hubs on the shortest path to a
    /// memory (the memory file not included).
    pub path_bytes_mean: f64,
    /// The most such bytes.
    pub path_bytes_max: usize,
    /// Reads to each memory reached (by stem).
    pub depth: BTreeMap<String, usize>,
    /// Everything wrong, one line each.
    pub problems: Vec<String>,
}

crate::impl_to_json!(Nav { leaves, hubs, root_lines, root_bytes, fanout_max, path_bytes_mean, path_bytes_max, problems });

/// Checks a memory folder's tree as a reader would walk it: every memory
/// file is reached in at most 3 reads after the root, pinned memories are in
/// the root, no memory is listed by two hubs (a pinned one also by the
/// root), every generated hub is reached, and no link dangles.
///
/// # Errors
///
/// [`Error::Io`] for an unreadable folder or root.
pub fn check(dir: &Path, index: &str, spec: &TreeSpec) -> Result<Nav> {
    let leaves = read_leaves_pinned(dir, index, spec)?;
    let root = read_text(&dir.join(index))?;
    let mut nav = Nav { leaves: leaves.len(), root_lines: root.lines().count(), root_bytes: root.len(), ..Nav::default() };
    let is_leaf: HashSet<&str> = leaves.iter().map(|l| l.stem.as_str()).collect();
    // Breadth first over files, as paths relative to the folder.
    let mut depth_of_leaf: HashMap<String, (usize, usize)> = HashMap::new();
    let mut hub_listings: HashMap<String, usize> = HashMap::new();
    let mut in_root: HashSet<String> = HashSet::new();
    let mut seen_hubs: HashMap<String, (usize, usize)> = HashMap::new();
    let mut queue: std::collections::VecDeque<(String, usize, usize)> = std::collections::VecDeque::from([(index.to_string(), 0usize, root.len())]);
    while let Some((rel, depth, bytes)) = queue.pop_front() {
        let text = if depth == 0 { root.clone() } else { std::fs::read_to_string(rel_path(dir, &rel)).unwrap_or_default() };
        let base: Vec<&str> = rel.split('/').collect();
        let base = &base[..base.len() - 1];
        let mut fan = 0;
        for l in text.lines() {
            let (target, to, ok) = match link(l) {
                Some((_, target, _)) => {
                    if target.contains("://") || !target.ends_with(".md") {
                        continue;
                    }
                    let mut parts: Vec<&str> = base.to_vec();
                    let mut ok = true;
                    for c in target.split('/') {
                        match c {
                            ".." => ok &= parts.pop().is_some(),
                            "." | "" => {}
                            c => parts.push(c),
                        }
                    }
                    (target.to_string(), parts.join("/"), ok)
                }
                None if spec.format == LineFormat::Slug => {
                    let Some((x, _)) = slug_entry(l) else { continue };
                    let (memory, hub) = (format!("{x}.md"), format!("{}/{x}.md", spec.hub_dir));
                    // The root names branches first; a hub names memories first.
                    let order = if depth == 0 { [&hub, &memory] } else { [&memory, &hub] };
                    let to = order.iter().find(|r| rel_path(dir, r).is_file()).map_or(memory.clone(), |r| (*r).clone());
                    (x.to_string(), to, true)
                }
                None => continue,
            };
            if !ok || !rel_path(dir, &to).is_file() {
                nav.problems.push(format!("{rel}: link to {target} dangles"));
                continue;
            }
            let parts: Vec<&str> = to.split('/').collect();
            fan += 1;
            let stem = to.strip_suffix(".md").unwrap_or(&to);
            if parts.len() == 1 && is_leaf.contains(stem) {
                if depth == 0 {
                    in_root.insert(stem.to_string());
                } else {
                    *hub_listings.entry(stem.to_string()).or_default() += 1;
                }
                let e = depth_of_leaf.entry(stem.to_string()).or_insert((usize::MAX, 0));
                if depth + 1 < e.0 {
                    *e = (depth + 1, bytes);
                }
            } else if parts.first() == Some(&spec.hub_dir.as_str()) && !seen_hubs.contains_key(&to) {
                let size = std::fs::metadata(rel_path(dir, &to)).map(|m| m.len() as usize).unwrap_or(0);
                seen_hubs.insert(to.clone(), (depth + 1, bytes + size));
                queue.push_back((to, depth + 1, bytes + size));
            }
        }
        if depth > 0 {
            nav.fanout_max = nav.fanout_max.max(fan);
            if fan > spec.hub_max {
                nav.problems.push(format!("{rel}: {fan} lines, over hub_max {}", spec.hub_max));
            }
        }
    }
    nav.hubs = seen_hubs.len();
    let mut total = 0usize;
    for l in &leaves {
        match depth_of_leaf.get(&l.stem) {
            None => nav.problems.push(format!("{}.md: not reachable from the root", l.stem)),
            Some(&(d, b)) => {
                nav.depth.insert(l.stem.clone(), d);
                nav.reads[d.min(4)] += 1;
                if d > 3 {
                    nav.problems.push(format!("{}.md: {d} reads from the root", l.stem));
                }
                total += b;
                nav.path_bytes_max = nav.path_bytes_max.max(b);
            }
        }
        let n = hub_listings.get(&l.stem).copied().unwrap_or(0);
        if n > 1 {
            nav.problems.push(format!("{}.md: listed by {n} hubs", l.stem));
        }
        if l.pinned && !in_root.contains(&l.stem) {
            nav.problems.push(format!("{}.md: pinned but not in the root", l.stem));
        }
        if !l.pinned && in_root.contains(&l.stem) {
            nav.problems.push(format!("{}.md: in the root but not pinned (filed on the next rescan)", l.stem));
        }
        if l.pinned && n == 0 {
            nav.problems.push(format!("{}.md: pinned but in no branch", l.stem));
        }
    }
    nav.path_bytes_mean = if leaves.is_empty() { 0.0 } else { total as f64 / leaves.len() as f64 };
    if let Ok(rd) = std::fs::read_dir(dir.join(&spec.hub_dir)) {
        let mut orphans: Vec<String> = rd
            .flatten()
            .map(|e| format!("{}/{}", spec.hub_dir, e.file_name().to_string_lossy()))
            .filter(|r| r.ends_with(".md") && !seen_hubs.contains_key(r))
            .filter(|r| std::fs::read_to_string(rel_path(dir, r)).is_ok_and(|t| t.contains(MARKER)))
            .collect();
        orphans.sort();
        for o in orphans {
            nav.problems.push(format!("{o}: a generated hub no link reaches"));
        }
    }
    Ok(nav)
}

/// An embedder for the tree: the configured model when it loads, else
/// [`lexical_vectors`].
pub fn embedder(model: &Path, threads: usize) -> Box<Embed<'static>> {
    match crate::embed::Model::load(model) {
        Ok(m) => Box::new(move |texts: &[String]| m.embed_many(texts, threads)),
        Err(_) => Box::new(|texts: &[String]| lexical_vectors(texts)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_cut_ends_on_a_whole_word_without_trailing_punctuation() {
        let c = cap_line("- x: frame targets, lockstep sim, perf rules and more words here", 30);
        assert_eq!(c, "- x: frame targets, lockstep");
        let c = cap_line("- x: he wants design questions put to him as multiple choice", 38);
        assert_eq!(c, "- x: he wants design questions put");
    }

    #[test]
    fn a_cut_line_is_a_prefix_cut_at_a_space() {
        let l = "- [Title](t.md) - one two three four five six seven eight nine ten eleven";
        let c = cap_line(l, 50);
        assert!(l.starts_with(&c) && c.chars().count() <= 50 && !c.ends_with(' '), "{c}");
        assert_eq!(cap_line("short", 50), "short");
    }

    #[test]
    fn words_and_types_score_branches() {
        let b = BranchSpec { name: "art".into(), title: "Art".into(), hook: String::new(), words: vec!["rig*".into(), "mesh".into()], types: vec!["reference".into()], repo: None };
        let l = leaf("rigs-need-bones", "---\nname: x\ndescription: a mesh note\nmetadata:\n  type: reference\n---\nbody\n");
        assert_eq!(score(&b, &l), 3 + 1 + 2);
        assert!(!hit("brig", "rig*"));
    }

    #[test]
    fn kmeans_is_capped_and_separates_clear_groups() {
        let mut v = Vec::new();
        for i in 0..10 {
            v.push(vec![1.0, 0.01 * i as f32, 0.0]);
            v.push(vec![0.0, 0.01 * i as f32, 1.0]);
        }
        for x in &mut v {
            normalize(x);
        }
        let a = kmeans(&v, 2, 12);
        for i in 0..10 {
            assert_eq!(a[2 * i], a[0]);
            assert_eq!(a[2 * i + 1], a[1]);
        }
        assert_ne!(a[0], a[1]);
    }
}
